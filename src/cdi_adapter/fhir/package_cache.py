"""Frozen FHIR package cache for the HL7 validator (backlog E6-S1 / E6-S5; ARCHITECTURE §6, §12).

The validator resolves the ABDM IG and every package it depends on (FHIR core, THO terminology,
extensions, and a few the validator adds itself) from ``<home>/.fhir/packages/<id>#<version>/``.
Left alone it fetches whatever is current, so the set is pinned here: ``infra/fhir/packages.lock``
lists every ``id#version`` with a digest of its files. A boot (E1-S4 style) or an IG upgrade
(E6-S5) seeds the cache once, then ``check`` proves it is exactly the pinned set; validation itself
always runs offline.

    python -m cdi_adapter.fhir.package_cache manifest --home /workspace/tools/fhir-home
    python -m cdi_adapter.fhir.package_cache check --home ... --lock infra/fhir/packages.lock
    python -m cdi_adapter.fhir.package_cache lock --home ... --lock ... --ig ndhm.in#6.5.0

Stdlib only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

# files the validator writes into a package after installing it: never part of the digest
GENERATED = frozenset({".index.json", ".index.db"})
_PKG_DIR = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*#[A-Za-z0-9][A-Za-z0-9._+-]*$")


def packages_dir(home: str | Path) -> Path:
    return Path(home) / ".fhir" / "packages"


def digest_package(pkg_dir: Path) -> str:
    """sha256 over the package's own files (relative path + content), in sorted order."""
    h = hashlib.sha256()
    root = pkg_dir / "package"
    # The existing pins were created on Windows, whose Path ordering ignores case.
    # Specify that ordering on every host; preserve original path bytes in the digest.
    files = sorted(
        (p for p in root.rglob("*") if p.is_file() and p.name not in GENERATED),
        key=lambda p: (
            tuple(part.lower() for part in p.relative_to(root).parts),
            p.relative_to(root).as_posix(),
        ),
    )
    for f in files:
        h.update(f.relative_to(root).as_posix().encode() + b"\0")
        h.update(hashlib.sha256(f.read_bytes()).digest())
    return h.hexdigest()


def manifest(home: str | Path) -> dict[str, str]:
    """``{id#version: digest}`` for every installed package (temp/partial folders ignored)."""
    base = packages_dir(home)
    if not base.is_dir():
        return {}
    return {d.name: digest_package(d) for d in sorted(base.iterdir())
            if d.is_dir() and _PKG_DIR.match(d.name) and (d / "package").is_dir()}  # fmt: skip


def read_lock(path: str | Path) -> dict[str, str]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    pkgs: dict[str, str] = data["packages"]
    return pkgs


def check(found: Mapping[str, str], pinned: Mapping[str, str]) -> list[str]:
    """Every way the cache differs from the lock, one line each (empty = exactly pinned)."""
    drift = [f"missing: {p}" for p in sorted(pinned.keys() - found.keys())]
    drift += [f"not pinned: {p}" for p in sorted(found.keys() - pinned.keys())]
    drift += [f"changed: {p} (digest {found[p][:12]}..., pinned {pinned[p][:12]}...)"
              for p in sorted(found.keys() & pinned.keys()) if found[p] != pinned[p]]  # fmt: skip
    return drift


def write_lock(path: str | Path, found: Mapping[str, str], *, ig: str, validator: str) -> None:
    data = {
        "_comment": "GENERATED by `python -m cdi_adapter.fhir.package_cache lock` (backlog "
        "E6-S1/E6-S5). The exact FHIR package set the HL7 validator uses; change only through "
        "the IG upgrade procedure (docs/ig-upgrade.md).",
        "ig": ig,
        "validator": validator,
        "packages": dict(sorted(found.items())),
    }
    Path(path).write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m cdi_adapter.fhir.package_cache",
                                 description=__doc__.splitlines()[0])  # fmt: skip
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("manifest", "check", "lock"):
        p = sub.add_parser(name)
        p.add_argument("--home", required=True, help="validator package home (CDI setting)")
        if name != "manifest":
            p.add_argument("--lock", required=True, help="infra/fhir/packages.lock")
        if name == "lock":
            p.add_argument("--ig", required=True)
            p.add_argument("--validator", required=True)
    args = ap.parse_args(argv)

    found = manifest(args.home)
    if args.cmd == "manifest":
        print(json.dumps(found, indent=2))
        return 0
    if args.cmd == "lock":
        write_lock(args.lock, found, ig=args.ig, validator=args.validator)
        print(f"locked {len(found)} packages -> {args.lock}")
        return 0
    drift = check(found, read_lock(args.lock))
    for line in drift:
        print(f"DRIFT: fhir package {line}")
    print("fhir packages: exactly the pinned set" if not drift else "fhir packages: drift")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
